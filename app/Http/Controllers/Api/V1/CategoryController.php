<?php

namespace App\Http\Controllers\Api\V1;

use App\Http\Controllers\Controller;
use App\Http\Requests\IndexCategoryRequest;
use App\Http\Requests\StoreCategoryRequest;
use App\Http\Requests\UpdateCategoryRequest;
use App\Http\Resources\CategoryResource;
use App\Models\Category;
use App\Traits\ApiResponseTrait;
use Illuminate\Http\JsonResponse;
use Illuminate\Support\Facades\Gate;

class CategoryController extends Controller
{
    use ApiResponseTrait;

    /**
     * List paginated categories with product counts.
     */
    public function index(IndexCategoryRequest $request): JsonResponse
    {
        Gate::authorize('viewAny', Category::class);

        $query = Category::withCount('products');

        $allowedSortColumns = ['id', 'name', 'slug', 'is_active', 'created_at', 'products_count'];
        $sortBy = in_array($request->input('sort_by'), $allowedSortColumns, true)
            ? $request->input('sort_by')
            : 'created_at';

        $direction = strtolower($request->input('direction', 'desc')) === 'asc' ? 'asc' : 'desc';
        $query->orderBy($sortBy, $direction);

        $perPage = min($request->integer('per_page', 10), 50);
        $perPage = $perPage > 0 ? $perPage : 10;

        $categories = $query->paginate($perPage);

        return $this->paginated(
            CategoryResource::collection($categories),
            'Categories retrieved successfully.'
        );
    }

    /**
     * Create a new category (slug auto-generated by model).
     */
    public function store(StoreCategoryRequest $request): JsonResponse
    {
        Gate::authorize('create', Category::class);

        $category = Category::create($request->validated());

        return $this->success(
            new CategoryResource($category),
            'Category created successfully.',
            201
        );
    }

    /**
     * Show a single category with its products.
     */
    public function show(Category $category): JsonResponse
    {
        Gate::authorize('view', $category);

        $category->load('products');

        return $this->success(
            new CategoryResource($category),
            'Category retrieved successfully.'
        );
    }

    /**
     * Update a category (slug auto-updated by model if name changes).
     */
    public function update(UpdateCategoryRequest $request, Category $category): JsonResponse
    {
        Gate::authorize('update', $category);

        $category->update($request->validated());

        return $this->success(
            new CategoryResource($category),
            'Category updated successfully.'
        );
    }

    /**
     * Delete a category.
     * Rejects deletion if products still belong to this category.
     */
    public function destroy(Category $category): JsonResponse
    {
        Gate::authorize('delete', $category);

        if ($category->products()->exists()) {
            return $this->error(
                'Cannot delete category because it still contains products. Please reassign or delete the products first.',
                409
            );
        }

        $category->delete();

        return $this->success(null, 'Category deleted successfully.');
    }

    /**
     * Restore a soft-deleted category.
     */
    public function restore(int|string $id): JsonResponse
    {
        $category = Category::onlyTrashed()->findOrFail($id);

        Gate::authorize('restore', $category);

        $category->restore();

        return $this->success(
            new CategoryResource($category),
            'Category restored successfully.'
        );
    }
}
